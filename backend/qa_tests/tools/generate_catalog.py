"""Generates docs/testing/TEST_CASES.md from the test modules (so the catalog cannot drift from the code).

    python -m qa_tests.tools.generate_catalog            (from backend/)
"""
import os
import re
import unittest

from qa_tests import _bootstrap  # noqa: F401
from qa_tests.run_suite import LEVELS

PREFIX = {"Unit Testing": "UT", "Integration Testing": "IT", "System / E2E Testing": "ST", "Boundary & Error Tests": "BT"}
SUBSYSTEM = {  # module or class name -> subsystem label used in the deck
    "TestPRNUWaveletExtraction": "PRNU wavelet extraction", "TestRPPGPeakDetection": "rPPG peak detection",
    "TestAxiomScoreWeighting": "Axiom score weighting", "TestJWTGeneration": "JWT generation",
    "test_02a_integration_api": "REST + authentication", "test_02b_integration_mongodb": "MongoDB session persistence",
    "test_02c_integration_redis": "Redis Pub/Sub", "test_02d_integration_websocket": "WebSocket frame ingestion",
    "test_02e_integration_rekognition": "AWS Rekognition",
    "test_03_e2e": "End-to-end workflow", "test_04_boundary": "Boundary / error",
}


def _humanize(method):
    words = re.sub(r"^test_\d+[a-z]?_", "", method).replace("_", " ")
    for acro in ("prnu", "aws", "jpeg", "json", "pos", "jwt", "rppg", "pdf", "bpm", "rest", "id", "ids"):
        words = re.sub(rf"\b{acro}\b", acro.upper() if acro != "ids" else "IDs", words)
    return words[0].upper() + words[1:]


def _cases(modules):
    out = []
    for mod in modules:
        suite = unittest.defaultTestLoader.loadTestsFromName(mod)
        stack = [suite]
        while stack:
            s = stack.pop()
            for t in s:
                if isinstance(t, unittest.TestSuite):
                    stack.append(t)
                else:
                    num = int(re.match(r"test_(\d+)", t._testMethodName).group(1))
                    sub = SUBSYSTEM.get(t.__class__.__name__) or SUBSYSTEM[mod.split(".")[-1]]
                    out.append((num, sub, _humanize(t._testMethodName), f"{mod.split('.')[-1]}.py::{t._testMethodName}"))
    return sorted(out, key=lambda x: (modules.index("qa_tests." + x[3].split(".py")[0]), x[0]))


def main():
    lines = ["# DeepVerify — Test Case Catalog", "",
             "Generated by `python -m qa_tests.tools.generate_catalog` from the test code. "
             "Every case is automated and calls the real application code.", ""]
    total = 0
    for level, modules, expected in LEVELS:
        cases = _cases(modules)
        total += len(cases)
        lines += [f"## {level} — {len(cases)} cases (deck: {expected})", "",
                  "| ID | Subsystem | Test case (objective / expected result) | Source |", "|---|---|---|---|"]
        for i, (_, sub, desc, src) in enumerate(cases, 1):
            lines.append(f"| {PREFIX[level]}-{i:02d} | {sub} | {desc} | `{src}` |")
        lines.append("")
    lines.append(f"**Total: {total} cases.**")
    path = os.path.join(os.path.dirname(__file__), "..", "..", "..", "docs", "testing", "TEST_CASES.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.normpath(path)} ({total} cases)")


if __name__ == "__main__":
    main()
